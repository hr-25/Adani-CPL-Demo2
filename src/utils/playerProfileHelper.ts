/**
 * Maps system Role to CPL Registration Playing Category
 */
export const mapRoleToCategory = (role: Role): PlayingCategory => {
  switch (role) {
    case 'Batter':
      return 'Batsman';
    case 'Bowler':
      return 'Bowler';
    case 'All-Rounder':
      return 'All-Rounder';
    case 'Wicketkeeper':
      return 'Wicket Keeper';
    default:
      return 'Batsman';
  }
};

/**
 * Mask mobile number for non-admin viewers to protect employee privacy
 */
export const maskMobileNumber = (mobile?: string): string => {
  if (!mobile) return 'Not Provided';
  const trimmed = mobile.trim();
  const parts = trimmed.split(' ');
  if (parts.length >= 3) {
    return `${parts[0]} ${parts[1].slice(0, 2)}*** ${parts[2]}`;
  }
  if (trimmed.length >= 10) {
    return trimmed.slice(0, 5) + '*** ' + trimmed.slice(-4);
  }
  return '••••••••••';
};

/**
 * Mask email address for non-admin viewers
 */
export const maskEmail = (email?: string): string => {
  if (!email) return 'Not Provided';
  const parts = email.split('@');
  if (parts.length === 2) {
    const user = parts[0];
    const domain = parts[1];
    if (user.length <= 2) {
      return `${user}***@${domain}`;
    }
    const prefix = user.substring(0, 2);
    const suffix = user.substring(user.length - 1);
    return `${prefix}***${suffix}@${domain}`;
  }
  return '••••@adani.com';
};

