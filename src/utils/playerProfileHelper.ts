/**
 * Returns complete registration profile for any player, falling back to deterministic
 * template if player object doesn't already have one embedded.
 */
export const getPlayerProfile = (player: Player): PlayerRegistrationProfile => {
  if (player.registrationProfile) {
    return player.registrationProfile;
  }

  const mapped = PLAYER_PROFILES_MAP[player.id];
  if (mapped) {
    return mapped;
  }

  // Fallback generator for dynamically created/added players
  const category = mapRoleToCategory(player.role);
  const isLeftHand = player.specialism.toLowerCase().includes('left hand');
  const isSpin =
    player.specialism.toLowerCase().includes('spin') ||
    player.specialism.toLowerCase().includes('orthodox') ||
    player.specialism.toLowerCase().includes('googly');
  const isFast =
    player.specialism.toLowerCase().includes('fast') ||
    player.specialism.toLowerCase().includes('pace') ||
    player.specialism.toLowerCase().includes('135') ||
    player.specialism.toLowerCase().includes('140');

  const bowlingStyle: BowlingStyle =
    player.role === 'Batter' || player.role === 'Wicketkeeper'
      ? 'NA'
      : isFast
      ? 'Fast'
      : isSpin
      ? 'Spin'
      : 'Medium';

  return {
    fullName: player.name,
    employeeId: `AD-2026-${player.lotNumber.toString().padStart(3, '0')}`,
    department: player.department,
    workLocation: `${player.cluster}, Gujarat`,
    mobileNumber: `+91 98250 ${player.lotNumber.toString().padStart(5, '0')}`,
    email: `${player.name.toLowerCase().replace(/\s+/g, '.')}@adani.com`,
    participationConfirmed: true,
    rolePreference: player.tier === 'Marquee' ? 'Captain' : 'Player',
    primaryCategory: category,
    battingStyle: isLeftHand ? 'Left Hand' : 'Right Hand',
    bowlingStyle,
    experienceLevel: player.tier === 'Marquee' || player.tier === 'Elite' ? 'Advanced' : 'Intermediate',
    previousRepresentation: player.previousTournament || undefined,
    battingRating: player.role === 'Batter' ? 5 : player.role === 'All-Rounder' ? 4 : 2,
    bowlingRating: player.role === 'Bowler' ? 5 : player.role === 'All-Rounder' ? 4 : 1,
    fieldingRating: player.role === 'Wicketkeeper' ? 5 : 4,
    overallRating: player.tier === 'Marquee' ? 9.2 : player.tier === 'Elite' ? 8.4 : 7.6,
    achievements: player.previousTournament,
    medicalClearance: true,
    fitnessStatus: 'Fully Fit — Cleared for all matches',
    injuryHistory: undefined,
    emergencyContactRelation: 'Spouse',
    isDemoSampleData: true,
  };
};
